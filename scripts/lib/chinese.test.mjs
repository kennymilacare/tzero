/** The simplified characters in a piece of writing. */
function simplifiedIn(text) {
  const found = new Set();
  for (const ch of String(text ?? '')) {
    if (SIMPLIFIED.has(ch)) found.add(ch);
  }
  return [...found];
}

/** Every string under a "zh" key, however deep it is. */
function chineseWords(value, out = []) {
  if (value == null || typeof value === 'string') return out;
  if (Array.isArray(value)) {
    value.forEach((v) => chineseWords(v, out));
    return out;
  }
  if (typeof value === 'object') {
    for (const [key, v] of Object.entries(value)) {
      if (key === 'zh' && typeof v === 'string') out.push(v);
      else chineseWords(v, out);
    }
  }
  return out;
}

/* ---------- the Chinese pages ---------- */

test('the Chinese pages have no simplified characters in them', async () => {
  const names = (await readdir(ROOT)).filter((n) => n.endsWith('.html')).sort();

  for (const name of names) {
    const html = await readFile(path.join(ROOT, name), 'utf8');
    const text = html
      .replace(/<script[\s\S]*?<\/script>/g, '')
      .replace(/<style[\s\S]*?<\/style>/g, '')
      .replace(/<[^>]+>/g, ' ');

    const found = simplifiedIn(text);
    assert.equal(found.length, 0,
      `${name}: "${found.join('", "')}" — mainland Chinese, where Hong Kong Chinese writes it differently`);
  }
});

/* ---------- the words that are written, not rendered ---------- */

test('the Chinese words are not mainland Chinese', () => {
  const strings = [];
  for (const [key, value] of Object.entries(i18n.zh)) {
    strings.push([`i18n.zh["${key}"]`, String(value)]);
  }
  for (const guide of GUIDES) {
    chineseWords(guide).forEach((s, i) => strings.push([`guide ${guide.slug}[${i}]`, s]));
  }

  for (const [where, text] of strings) {
    const found = simplifiedIn(text);
    assert.equal(found.length, 0,
      `${where}: "${found.join('", "')}" — mainland Chinese, where Hong Kong Chinese writes it differently`);
  }
});
