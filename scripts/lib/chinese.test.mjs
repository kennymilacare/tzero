/* ===========================================================
   The checks that keep the Chinese Traditional.

   The site is written in Traditional Chinese for Hong Kong.
   A character that only exists in mainland Chinese — 什么 for
   什麼, 国际 for 國際 — slips in easily and reads as a mistake
   to a Hong Kong reader, and to Google, which serves the page
   to somebody searching in Traditional Chinese.

   The eye does not catch it. 什么 is what half the machine
   translations on the internet say, so it reads as normal. The
   script does catch it, and so does this test.

   Characters that are perfectly good in Traditional Chinese
   are deliberately absent: 划 (划算), 卡 (信用卡), 南 (指南),
   向 (方向), 内 (內), 困 (困難). They are not simplifications.

   Run: node --test scripts/lib/chinese.test.mjs
   =========================================================== */

