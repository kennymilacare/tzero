/* ===========================================================
   scripts/lib/seo.mjs — the parts of the SEO work that have to
   agree with each other.

   The FAQ is written in two places: in the markup of index.html
   (so a crawler can read it) and in the FAQPage block of the
   structured data (so Google can use it). Both come from the same
   list in assets/js/data.js, so they cannot drift apart.

   Pure helpers only — no filesystem, no network.
   =========================================================== */

import { faqHTML } from '../../assets/js/faq.js';

/* The comment that marks the generated block in index.html. */
export const FAQ_MARKER = `          <!-- GENERATED by scripts/gen-faq-html.mjs — do not edit by hand.
               The questions are in the markup so a crawler can read them
               without running any JavaScript. The page replaces this
               block with the same questions in the visitor's language. -->`;

/**
 * The FAQ block for index.html, in Chinese — the language the page
 * starts in. The page replaces it with the visitor's language.
 */
export function faqBlock(faqs) {
  const items = faqHTML(faqs, (item, key) => item[`${key}_zh`]).replace(/^\n/, '');
  return `${FAQ_MARKER}\n${items}\n`;
}

/**
 * The FAQPage node for one language.
 *
 * The same shape as the faqPage() helper in assets/js/data.js — the
 * structured data there is built from the same list, so this is only
 * used to check the two agree.
 */
export function faqPageNode(faqs, lang) {
  return {
    '@type': 'FAQPage',
    mainEntity: faqs.map((f) => ({
      '@type': 'Question',
      name: f[`q_${lang}`],
      acceptedAnswer: { '@type': 'Answer', text: f[`a_${lang}`] },
    })),
  };
}
